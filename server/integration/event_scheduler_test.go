// stubSuggest returns five fixed titles, so the scheduler never calls TMDB.
func stubSuggest(_ context.Context, mediaType, _ string) ([]event_module.SuggestedNominee, error) {
	out := make([]event_module.SuggestedNominee, 0, 5)
	for i := 1; i <= 5; i++ {
		out = append(out, event_module.SuggestedNominee{
			MediaID: 9000 + i, MediaType: mediaType, MediaTitle: fmt.Sprintf("Pick %d", i),
		})
	}
	return out, nil
}

func schedulerAt(db *gorm.DB, at time.Time) *event_module.RoundScheduler {
	return event_module.NewRoundSchedulerWith(db, func() time.Time { return at }, stubSuggest)
}

func bkk(y int, m time.Month, d, h, min int) time.Time {
	return time.Date(y, m, d, h, min, 0, 0, config.AppLocation)
}

// roundCount counts rounds (soft-deleted included) of one type, media type and period.
func roundCount(e *env, typ, mediaType, period string) int64 {
	return e.count(`SELECT COUNT(*) FROM events WHERE type = ? AND media_type = ? AND period = ?`, typ, mediaType, period)
}

func eventStatus(t *testing.T, db *gorm.DB, id uint) string {
	t.Helper()
	var s string
	if err := db.Raw(`SELECT status FROM events WHERE id = ?`, id).Scan(&s).Error; err != nil {
		t.Fatal(err)
	}
	return s
}

// A draft appears only once the round is within the lead window, is flagged auto_generated, and
// its audit row has no admin.
func TestRoundSchedulerGeneratesInsideLeadWindowOnly(t *testing.T) {
	e := newEnv(t)
	ctx := context.Background()
	seedDeletedRounds(t, e, "2026-05") // the CURRENT round: keep the catch-up out of this test

	// Next monthly round is 2026-06 (opens 15 June 00:00 Bangkok); the lead is 72h.
	generated, published, err := schedulerAt(e.db, bkk(2026, 6, 11, 23, 0)).RunOnce(ctx)
	if err != nil || generated != 0 || published != 0 {
		t.Fatalf("before the lead window: want nothing, got generated=%d published=%d err=%v", generated, published, err)
	}
	if n := e.count(`SELECT COUNT(*) FROM events WHERE deleted_at IS NULL`); n != 0 {
		t.Fatalf("expected no rows before the lead window, got %d", n)
	}

	generated, _, err = schedulerAt(e.db, bkk(2026, 6, 12, 0, 0)).RunOnce(ctx)
	if err != nil || generated != 2 {
		t.Fatalf("inside the lead window: want movie and tv drafts, got generated=%d err=%v", generated, err)
	}
	for _, mt := range []string{"movie", "tv"} {
		if n := e.count(`SELECT COUNT(*) FROM events WHERE type = 'vote_monthly' AND media_type = ? AND period = '2026-06'
			AND status = 'draft' AND auto_generated`, mt); n != 1 {
			t.Errorf("%s: want one auto draft, got %d", mt, n)
		}
	}
	if n := e.count(`SELECT COUNT(*) FROM admin_audit_logs WHERE action = ? AND admin_id IS NULL`,
		string(admin_module.ActionEventAutoGenerated)); n != 2 {
		t.Errorf("want 2 system audit rows, got %d", n)
	}

	// A second pass finds the rounds and creates nothing.
	if generated, _, err := schedulerAt(e.db, bkk(2026, 6, 12, 0, 5)).RunOnce(ctx); err != nil || generated != 0 {
		t.Fatalf("second pass: want 0 generated and no error, got %d, %v", generated, err)
	}
}

func TestRoundSchedulerConcurrentRunsCreateOneRow(t *testing.T) {
	e := newEnv(t)
	at := bkk(2026, 6, 13, 0, 0)

	var wg sync.WaitGroup
	errs := make(chan error, 4)
	for i := 0; i < 4; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			_, _, err := schedulerAt(e.db, at).RunOnce(context.Background())
			errs <- err
		}()
	}
	wg.Wait()
	close(errs)
	for err := range errs {
		if err != nil {
			t.Errorf("concurrent pass failed: %v", err)
		}
	}
	for _, mt := range []string{"movie", "tv"} {
		if n := roundCount(e, "vote_monthly", mt, "2026-06"); n != 1 {
			t.Errorf("%s: want exactly one round, got %d", mt, n)
		}
	}
}

func TestRoundSchedulerNeverRecreatesDeletedDraft(t *testing.T) {
	e := newEnv(t)
	ctx := context.Background()
	at := bkk(2026, 6, 13, 0, 0)

	if _, _, err := schedulerAt(e.db, at).RunOnce(ctx); err != nil {
		t.Fatal(err)
	}
	if err := e.db.Where("1 = 1").Delete(&event_module.Event{}).Error; err != nil {
		t.Fatal(err)
	}
	generated, _, err := schedulerAt(e.db, at.Add(time.Hour)).RunOnce(ctx)
	if err != nil || generated != 0 {
		t.Fatalf("want deleted drafts left deleted, got generated=%d err=%v", generated, err)
	}
	if n := roundCount(e, "vote_monthly", "movie", "2026-06"); n != 1 {
		t.Errorf("want only the soft-deleted row, got %d rows", n)
	}
}

// Only auto drafts with enough nominees, inside the publish lead, are published.
func TestRoundSchedulerAutoPublish(t *testing.T) {
	e := newEnv(t)
	ctx := context.Background()
	seedDeletedRounds(t, e, "2026-05") // the CURRENT round: keep the catch-up out of this test
	at := bkk(2026, 6, 1, 12, 0)       // no round is within its generate lead
	starts, ends := at.Add(2*time.Minute), at.Add(30*24*time.Hour)

	seed := func(period, mediaType string, status event_module.EventStatus, auto bool, nominees int) uint {
		id := seedEvent(t, e.db, event_module.Event{
			Type: event_module.TypeVoteMonthly, MediaType: strRef(mediaType), Period: strRef(period),
			StartsAt: starts, EndsAt: ends, Status: status, AutoGenerated: auto, AutoPublish: auto,
		})
		for i := 0; i < nominees; i++ {
			seedNominee(t, e.db, id, mediaType, i+1, 100+i, "", "")
		}
		return id
	}
	ready := seed("2026-01", "movie", event_module.StatusDraft, true, 2)
	tooFew := seed("2026-02", "movie", event_module.StatusDraft, true, 1)
	cancelled := seed("2026-03", "movie", event_module.StatusCancelled, true, 3)
	adminDraft := seed("2026-04", "movie", event_module.StatusDraft, false, 3)
	notDue := seedEvent(t, e.db, event_module.Event{
		Type: event_module.TypeVoteMonthly, MediaType: strRef("tv"), Period: strRef("2025-05"),
		StartsAt: at.Add(time.Hour), EndsAt: ends, Status: event_module.StatusDraft, AutoGenerated: true, AutoPublish: true,
	})
	seedNominee(t, e.db, notDue, "tv", 1, 1, "", "")
	seedNominee(t, e.db, notDue, "tv", 2, 2, "", "")

	generated, published, err := schedulerAt(e.db, at).RunOnce(ctx)
	if err != nil || generated != 0 || published != 1 {
		t.Fatalf("want exactly one publish, got generated=%d published=%d err=%v", generated, published, err)
	}
	want := map[string]struct {
		id     uint
		status string
	}{
		"ready":      {ready, "published"},
		"tooFew":     {tooFew, "draft"},
		"cancelled":  {cancelled, "cancelled"},
		"adminDraft": {adminDraft, "draft"},
		"notYetDue":  {notDue, "draft"},
	}
	for name, w := range want {
		if got := eventStatus(t, e.db, w.id); got != w.status {
			t.Errorf("%s: want %s, got %s", name, w.status, got)
		}
	}
	if n := e.count(`SELECT COUNT(*) FROM admin_audit_logs WHERE action = ? AND admin_id IS NULL AND target_id = ?`,
		string(admin_module.ActionEventAutoPublished), ready); n != 1 {
		t.Errorf("want one system publish audit row, got %d", n)
	}
}

// A yearly round waits for every published monthly round of its year to settle, then takes the
// monthly winners as nominees, one entry per title, most wins first.
func TestRoundSchedulerYearlyWaitsForMonthlyAndDedupes(t *testing.T) {
	e := newEnv(t)
	ctx := context.Background()
	at := bkk(2027, 1, 14, 12, 0) // yearly 2026 opens 16 Jan; inside the generate lead

	round := func(period string, finalized bool) uint {
		starts := bkk(2026, 1, 1, 0, 0)
		return seedEvent(t, e.db, event_module.Event{
			Type: event_module.TypeVoteMonthly, MediaType: strRef("movie"), Period: strRef(period),
			StartsAt: starts, EndsAt: starts.AddDate(0, 1, 0), Status: event_module.StatusPublished, IsFinalized: finalized,
		})
	}
	win := func(eventID uint, period string, mediaID, votes int) {
		n := seedNominee(t, e.db, eventID, "movie", 1, mediaID, "", "")
		seedAward(t, e.db, eventID, n, mediaID, "movie", event_module.AwardKindMonthly, period, votes)
	}
	mar, may := round("2026-03", true), round("2026-05", true)
	win(mar, "2026-03", 100, 4)
	win(mar, "2026-03", 200, 4) // co-winner of March
	win(may, "2026-05", 100, 7)
	dec := round("2026-12", false)

	if _, _, err := schedulerAt(e.db, at).RunOnce(ctx); err != nil {
		t.Fatal(err)
	}
	if n := roundCount(e, "vote_yearly", "movie", "2026"); n != 0 {
		t.Fatalf("yearly movie round must wait for the pending December round, got %d", n)
	}

	if err := e.db.Exec(`UPDATE events SET is_finalized = true WHERE id = ?`, dec).Error; err != nil {
		t.Fatal(err)
	}
	if _, _, err := schedulerAt(e.db, at.Add(time.Minute)).RunOnce(ctx); err != nil {
		t.Fatal(err)
	}
	var ids []int
	if err := e.db.Raw(`SELECT n.media_id FROM event_nominees n JOIN events ev ON ev.id = n.event_id
		WHERE ev.type = 'vote_yearly' AND ev.media_type = 'movie' AND ev.period = '2026' AND ev.auto_generated
		ORDER BY n.position`).Scan(&ids).Error; err != nil {
		t.Fatal(err)
	}
	if len(ids) != 2 || ids[0] != 100 || ids[1] != 200 {
		t.Fatalf("want nominees [100 200] (deduped, most wins first), got %v", ids)
	}
	// TV had no monthly winners: too few nominees, so no row is created.
	if n := roundCount(e, "vote_yearly", "tv", "2026"); n != 0 {
		t.Errorf("want no yearly tv round, got %d rows", n)
	}
}

// A yearly round settles into award_kind yearly; ties share the award and no votes means no award.
func TestYearlyFinalizeAwardsKindYearlyTiesAndNoVotes(t *testing.T) {
	e := newEnv(t)
	now := time.Now().UTC()
	u1 := seedUser(t, e.db, "y1@x.test", true, "pw")
	u2 := seedUser(t, e.db, "y2@x.test", true, "pw")

	yearly := func(mediaType string) (uint, uint, uint) {
		id := seedEvent(t, e.db, event_module.Event{
			Type: event_module.TypeVoteYearly, MediaType: strRef(mediaType), Period: strRef("2026"),
			StartsAt: now.Add(-30 * 24 * time.Hour), EndsAt: now.Add(-time.Hour), Status: event_module.StatusPublished,
		})
		return id, seedNominee(t, e.db, id, mediaType, 1, 11, "", ""), seedNominee(t, e.db, id, mediaType, 2, 22, "", "")
	}
	movie, a, b := yearly("movie")
	for uid, nominee := range map[uint]uint{u1: a, u2: b} {
		if err := e.db.Exec(`INSERT INTO event_votes (event_id, user_id, nominee_id, created_at, updated_at) VALUES (?, ?, ?, now(), now())`,
			movie, uid, nominee).Error; err != nil {
			t.Fatal(err)
		}
	}
	tv, _, _ := yearly("tv")

	if settled, err := event_module.NewFinalizer(e.db, nil).RunOnce(context.Background()); err != nil || settled != 2 {
		t.Fatalf("want 2 rounds settled, got %d, %v", settled, err)
	}
	if n := e.count(`SELECT COUNT(*) FROM event_awards WHERE event_id = ? AND award_kind = 'yearly' AND period = '2026'`, movie); n != 2 {
		t.Errorf("tie: want 2 yearly co-winners, got %d", n)
	}
	if n := e.count(`SELECT COUNT(*) FROM event_awards WHERE event_id = ?`, tv); n != 0 {
		t.Errorf("no votes: want no award, got %d", n)
	}
}

func TestGenerateYearlyEndpoint(t *testing.T) {
	e := newEnv(t)
	e.seedAdmin("yadmin@x.test", "pw-admin")
	tok := e.loginPair("yadmin@x.test", "pw-admin").AccessToken
	period := event_module.NextYearlyPeriod(time.Now())

	code, out := e.do("POST", "/api/admin/events/generate-yearly", map[string]any{"media_type": "movie"}, tok)
	if code != 409 || out["code"] != "TOO_FEW_YEARLY_NOMINEES" {
		t.Fatalf("no monthly winners: want 409 TOO_FEW_YEARLY_NOMINEES, got %d: %v", code, out)
	}
	if n := roundCount(e, "vote_yearly", "movie", period); n != 0 {
		t.Fatalf("a refused yearly round must not leave a row, got %d", n)
	}
	monthly := seedEvent(t, e.db, event_module.Event{
		Type: event_module.TypeVoteMonthly, MediaType: strRef("movie"), Period: strRef(period + "-03"),
		StartsAt: time.Now().UTC(), EndsAt: time.Now().UTC().AddDate(0, 1, 0), Status: event_module.StatusPublished, IsFinalized: true,
	})
	for i, mediaID := range []int{100, 200} {
		n := seedNominee(t, e.db, monthly, "movie", i+1, mediaID, "", "")
		seedAward(t, e.db, monthly, n, mediaID, "movie", event_module.AwardKindMonthly, period+"-03", 4)
	}
	code, out = e.do("POST", "/api/admin/events/generate-yearly", map[string]any{"media_type": "movie"}, tok)
	if code != 201 {
		t.Fatalf("want 201, got %d: %v", code, out)
	}
	ev := out["event"].(map[string]any)
	if ev["type"] != "vote_yearly" || ev["period"] != period || ev["status"] != "draft" || ev["auto_generated"] != false {
		t.Errorf("unexpected event: %v", ev)
	}

	code, out = e.do("POST", "/api/admin/events/generate-yearly", map[string]any{"media_type": "movie", "period": period}, tok)
	if code != 409 || out["code"] != "EVENT_ALREADY_EXISTS" {
		t.Errorf("duplicate: want 409 EVENT_ALREADY_EXISTS, got %d: %v", code, out)
	}

	starts := time.Now().UTC()
	seedEvent(t, e.db, event_module.Event{
		Type: event_module.TypeVoteMonthly, MediaType: strRef("tv"), Period: strRef(period + "-06"),
		StartsAt: starts, EndsAt: starts.AddDate(0, 1, 0), Status: event_module.StatusPublished,
	})
	code, out = e.do("POST", "/api/admin/events/generate-yearly", map[string]any{"media_type": "tv"}, tok)
	if code != 409 || out["code"] != "MONTHLY_ROUNDS_PENDING" {
		t.Errorf("pending monthly: want 409 MONTHLY_ROUNDS_PENDING, got %d: %v", code, out)
	}

	code, out = e.do("POST", "/api/admin/events/generate-yearly", map[string]any{"media_type": "movie", "period": "20x6"}, tok)
	if code != 400 {
		t.Errorf("bad period: want 400, got %d: %v", code, out)
	}
	code, out = e.do("POST", "/api/admin/events/generate-yearly", map[string]any{"media_type": "book"}, tok)
	if code != 400 {
		t.Errorf("bad media type: want 400, got %d: %v", code, out)
	}
}

// An auto draft that an admin soft-deletes between the scheduler's first existence check and its
// insert (simulated inside the nominee source) is not recreated: the insert transaction re-checks
// Unscoped under an advisory lock.
func TestRoundSchedulerDoesNotRecreateDraftDeletedMidFlight(t *testing.T) {
	e := newEnv(t)
	ctx := context.Background()
	at := bkk(2026, 6, 12, 12, 0)
	startsAt, endsAt, err := event_module.MonthlyWindow("2026-06")
	if err != nil {
		t.Fatal(err)
	}

	racing := func(ctx context.Context, mediaType, period string) ([]event_module.SuggestedNominee, error) {
		if mediaType == "movie" {
			if err := e.db.Exec(`INSERT INTO events (title_en, title_th, type, media_type, period, starts_at, ends_at, status, auto_generated, deleted_at, created_at, updated_at)
				VALUES ('', '', 'vote_monthly', 'movie', ?, ?, ?, 'draft', true, now(), now(), now())`, period, startsAt, endsAt).Error; err != nil {
				t.Fatal(err)
			}
		}
		return stubSuggest(ctx, mediaType, period)
	}
	sched := event_module.NewRoundSchedulerWith(e.db, func() time.Time { return at }, racing)
	if _, _, err := sched.RunOnce(ctx); err != nil {
		t.Fatalf("RunOnce: %v", err)
	}
	if n := roundCount(e, "vote_monthly", "movie", "2026-06"); n != 1 {
		t.Fatalf("deleted auto draft was recreated: %d rows", n)
	}
}
