// An auto_generated draft whose admin turned auto_publish off is not published by the worker.
func TestRoundSchedulerSkipsOptedOutDraft(t *testing.T) {
	e := newEnv(t)
	at := bkk(2026, 6, 1, 12, 0)
	mk := func(period string, autoPublish bool) uint {
		id := seedEvent(t, e.db, event_module.Event{
			Type: event_module.TypeVoteMonthly, MediaType: strRef("movie"), Period: strRef(period),
			StartsAt: at.Add(time.Minute), EndsAt: at.Add(30 * 24 * time.Hour), Status: event_module.StatusDraft,
			AutoGenerated: true, AutoPublish: autoPublish,
		})
		seedNominee(t, e.db, id, "movie", 1, 1, "", "")
		seedNominee(t, e.db, id, "movie", 2, 2, "", "")
		return id
	}
	optedOut, optedIn := mk("2026-01", false), mk("2026-02", true)
	if _, published, err := schedulerAt(e.db, at).RunOnce(context.Background()); err != nil || published != 1 {
		t.Fatalf("want one publish, got %d, %v", published, err)
	}
	if got := eventStatus(t, e.db, optedOut); got != "draft" {
		t.Errorf("opted-out draft: want draft, got %s", got)
	}
	if got := eventStatus(t, e.db, optedIn); got != "published" {
		t.Errorf("opted-in draft: want published, got %s", got)
	}
}

func TestSetAutoPublishEndpoint(t *testing.T) {
	e := newEnv(t)
	useFakeVotingTMDB(t, 6)
	e.seedAdmin("ap@x.test", "pw-admin")
	tok := e.loginPair("ap@x.test", "pw-admin").AccessToken
	period := event_module.NextMonthlyPeriod(time.Now())

	code, out := e.do("POST", "/api/admin/events/generate-monthly", map[string]any{"media_type": "movie", "period": period}, tok)
	if code != 201 {
		t.Fatalf("generate: %d %v", code, out)
	}
	ev := out["event"].(map[string]any)
	id := uint(ev["id"].(float64))
	if ev["auto_publish"] != false {
		t.Errorf("admin draft: want auto_publish=false, got %v", ev["auto_publish"])
	}
	path := fmt.Sprintf("/api/admin/events/%d", id)
	audits := func() int64 {
		return e.count(`SELECT COUNT(*) FROM admin_audit_logs WHERE action = ? AND target_id = ?`,
			string(admin_module.ActionEventAutoPublishChanged), id)
	}

	code, out = e.do("PATCH", path, map[string]any{"auto_publish": true}, tok)
	if code != 200 || out["event"].(map[string]any)["auto_publish"] != true {
		t.Fatalf("enable: want 200 true, got %d %v", code, out)
	}
	if audits() != 1 {
		t.Errorf("want one audit row, got %d", audits())
	}
	if n := e.count(`SELECT COUNT(*) FROM admin_audit_logs WHERE action = ? AND meta_data->>'from' = 'false' AND meta_data->>'to' = 'true'`,
		string(admin_module.ActionEventAutoPublishChanged)); n != 1 {
		t.Errorf("want from/to meta, got %d", n)
	}
	if code, _ = e.do("PATCH", path, map[string]any{"auto_publish": true}, tok); code != 200 || audits() != 1 {
		t.Errorf("same value: want 200 and no new audit row, got %d / %d", code, audits())
	}
	if code, out = e.do("PATCH", path, map[string]any{}, tok); code != 400 || out["code"] != "INVALID_INPUT" {
		t.Errorf("missing field: want 400 INVALID_INPUT, got %d %v", code, out)
	}
	if code, out = e.do("PATCH", "/api/admin/events/999999", map[string]any{"auto_publish": true}, tok); code != 404 {
		t.Errorf("unknown id: want 404, got %d %v", code, out)
	}

	// Ended draft: cannot be enabled.
	now := time.Now().UTC()
	setWindow(t, e, id, now.Add(-48*time.Hour), now.Add(-time.Hour))
	if code, _ = e.do("PATCH", path, map[string]any{"auto_publish": false}, tok); code != 200 {
		t.Fatalf("disable on ended draft: want 200, got %d", code)
	}
	if code, out = e.do("PATCH", path, map[string]any{"auto_publish": true}, tok); code != 409 || out["code"] != "VOTING_CLOSED" {
		t.Errorf("enable after end: want 409 VOTING_CLOSED, got %d %v", code, out)
	}

	// Not a draft.
	if err := e.db.Exec(`UPDATE events SET status = 'published' WHERE id = ?`, id).Error; err != nil {
		t.Fatal(err)
	}
	if code, out = e.do("PATCH", path, map[string]any{"auto_publish": true}, tok); code != 409 || out["code"] != "EVENT_NOT_DRAFT" {
		t.Errorf("published: want 409 EVENT_NOT_DRAFT, got %d %v", code, out)
	}

	// Not a voting round.
	ann := createEvent(t, e, tok, eventWindow(now, "draft", time.Hour, 48*time.Hour))
	if code, out = e.do("PATCH", fmt.Sprintf("/api/admin/events/%d", ann), map[string]any{"auto_publish": true}, tok); code != 400 || out["code"] != "INVALID_EVENT_TYPE" {
		t.Errorf("announcement: want 400 INVALID_EVENT_TYPE, got %d %v", code, out)
	}

	// Anonymous callers get nothing.
	if code, _ = e.do("PATCH", path, map[string]any{"auto_publish": true}, ""); code != 401 {
		t.Errorf("no token: want 401, got %d", code)
	}
}

// Moving a published round back to draft clears auto_publish, so it must be re-armed on purpose.
