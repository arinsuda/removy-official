// Fixed clocks: 2026-11 runs 15 Nov 00:00 -> 15 Dec 00:00 Bangkok.
var (
	lateEnds    = bkk(2026, time.December, 15, 0, 0)
	lateEnough  = bkk(2026, time.December, 1, 12, 0)  // 13.5 days left
	lateTooLate = bkk(2026, time.December, 12, 12, 0) // 60h left: under the 72h minimum
)

func clockSvc(db *gorm.DB, at time.Time) *event_module.Service {
	return event_module.NewServiceWithClock(db, nil, func() time.Time { return at })
}

// seedDeletedRounds inserts soft-deleted drafts for the CURRENT monthly round of both media types, so
// the worker's catch-up (which counts deleted rows) leaves them alone.
func seedDeletedRounds(t *testing.T, e *env, period string) {
	t.Helper()
	starts, ends, err := event_module.MonthlyWindow(period)
	if err != nil {
		t.Fatal(err)
	}
	for _, mt := range []string{"movie", "tv"} {
		if err := e.db.Exec(`INSERT INTO events (title_en, title_th, type, media_type, period, starts_at, ends_at, status, auto_generated, deleted_at, created_at, updated_at)
			VALUES ('', '', 'vote_monthly', ?, ?, ?, ?, 'draft', true, now(), now(), now())`, mt, period, starts, ends).Error; err != nil {
			t.Fatal(err)
		}
	}
}

func TestLateStartGenerateMonthly(t *testing.T) {
	e := newEnv(t)
	useFakeVotingTMDB(t, 6)
	adminID := e.seedAdmin("late@x.test", "pw-admin")
	ctx := context.Background()
	svc := clockSvc(e.db, lateEnough.Add(45*time.Second))

	ev, err := svc.GenerateMonthlyVote(ctx, adminID, "movie", "2026-11", true)
	if err != nil {
		t.Fatalf("late generate: %v", err)
	}
	wantStart := lateEnough.Add(time.Hour)
	if !ev.StartsAt.Equal(wantStart) || !ev.EndsAt.Equal(lateEnds) {
		t.Fatalf("window %v-%v, want %v-%v", ev.StartsAt, ev.EndsAt, wantStart, lateEnds)
	}
	if ev.Status != event_module.StatusDraft || ev.AutoPublish || ev.AutoGenerated {
		t.Errorf("want admin draft without auto flags, got %+v", ev)
	}
	if n := e.count(`SELECT COUNT(*) FROM admin_audit_logs WHERE action = ? AND target_id = ? AND meta_data->>'late_start' = 'true'`,
		string(admin_module.ActionEventCreated), ev.ID); n != 1 {
		t.Errorf("want late_start in the create audit meta, got %d rows", n)
	}

	// Nominees stay editable until the (future) opening, then freeze.
	noms := []event_module.NomineeInput{
		{MediaID: 1, MediaType: "movie", Position: 1, MediaTitle: "A"},
		{MediaID: 2, MediaType: "movie", Position: 2, MediaTitle: "B"},
	}
	if _, err := svc.SetNominees(ctx, adminID, ev.ID, noms); err != nil {
		t.Fatalf("set nominees before open: %v", err)
	}
	opened := clockSvc(e.db, wantStart)
	if _, err := opened.SetNominees(ctx, adminID, ev.ID, noms); !errors.Is(err, event_module.ErrVotingLocked) {
		t.Errorf("after opening want ErrVotingLocked, got %v", err)
	}

	// The round still finalizes at the official end.
	if err := e.db.Exec(`UPDATE events SET status = 'published' WHERE id = ?`, ev.ID).Error; err != nil {
		t.Fatal(err)
	}
	if err := clockSvc(e.db, lateEnds.Add(-time.Minute)).Finalize(ctx, adminID, ev.ID); !errors.Is(err, event_module.ErrVotingNotEnded) {
		t.Errorf("before ends_at want ErrVotingNotEnded, got %v", err)
	}
	if err := clockSvc(e.db, lateEnds).Finalize(ctx, adminID, ev.ID); err != nil {
		t.Errorf("at ends_at finalize: %v", err)
	}
}

func TestLateStartRefusals(t *testing.T) {
	e := newEnv(t)
	useFakeVotingTMDB(t, 6)
	adminID := e.seedAdmin("late2@x.test", "pw-admin")
	ctx := context.Background()

	// Too little time left.
	if _, err := clockSvc(e.db, lateTooLate).GenerateMonthlyVote(ctx, adminID, "movie", "2026-11", true); !errors.Is(err, event_module.ErrVotingWindowTooShort) {
		t.Errorf("too short: want ErrVotingWindowTooShort, got %v", err)
	}
	// Not the current period.
	var val *event_module.ValidationError
	if _, err := clockSvc(e.db, lateEnough).GenerateMonthlyVote(ctx, adminID, "movie", "2026-12", true); !errors.As(err, &val) || val.Field != "period" {
		t.Errorf("non-current: want invalid period, got %v", err)
	}
	// Yearly outside its window has no current round.
	if _, err := clockSvc(e.db, lateEnough).GenerateYearlyVote(ctx, adminID, "movie", "2025", true); !errors.As(err, &val) {
		t.Errorf("yearly outside window: want validation error, got %v", err)
	}
	// A cancelled current round still blocks a second one.
	starts, ends, _ := event_module.MonthlyWindow("2026-11")
	seedEvent(t, e.db, event_module.Event{
		Type: event_module.TypeVoteMonthly, MediaType: strRef("movie"), Period: strRef("2026-11"),
		StartsAt: starts, EndsAt: ends, Status: event_module.StatusCancelled,
	})
	if _, err := clockSvc(e.db, lateEnough).GenerateMonthlyVote(ctx, adminID, "movie", "2026-11", true); !errors.Is(err, event_module.ErrEventExists) {
		t.Errorf("cancelled current: want ErrEventExists, got %v", err)
	}
}

// Yearly late start inside the Jan 16 - Feb 15 window: opens lateStartLead from now, keeps the official end.
func TestLateStartGenerateYearly(t *testing.T) {
	e := newEnv(t)
	adminID := e.seedAdmin("late4@x.test", "pw-admin")
	now := bkk(2027, time.January, 20, 10, 30).Add(45 * time.Second)

	ev, err := clockSvc(e.db, now).GenerateYearlyVote(context.Background(), adminID, "movie", "2026", true)
	if err != nil {
		t.Fatalf("late yearly generate: %v", err)
	}
	wantStart, wantEnd := now.Truncate(time.Minute).Add(time.Hour), bkk(2027, time.February, 15, 0, 0)
	if !ev.StartsAt.Equal(wantStart) || !ev.EndsAt.Equal(wantEnd) {
		t.Fatalf("window %v-%v, want %v-%v", ev.StartsAt, ev.EndsAt, wantStart, wantEnd)
	}
	if ev.Period == nil || *ev.Period != "2026" || ev.Status != event_module.StatusDraft {
		t.Errorf("want draft for period 2026, got %+v", ev)
	}
}

func TestLateStartGenerateMonthlyHTTPAndMapping(t *testing.T) {
	e := newEnv(t)
	e.seedAdmin("late3@x.test", "pw-admin")
	tok := e.loginPair("late3@x.test", "pw-admin").AccessToken

	// The next monthly period is never the current one, whatever the real clock says.
	next := event_module.NextMonthlyPeriod(time.Now())
	code, out := e.do("POST", "/api/admin/events/generate-monthly", map[string]any{"media_type": "movie", "period": next, "late_start": true}, tok)
	if code != 400 || out["code"] != "INVALID_INPUT" {
		t.Errorf("non-current late start: want 400 INVALID_INPUT, got %d: %v", code, out)
	}
	// The current period: 201 when 73h+ remain, else 409 VOTING_WINDOW_TOO_SHORT.
	useFakeVotingTMDB(t, 6)
	cur := event_module.CurrentMonthlyPeriod(time.Now())
	_, endsAt, _ := event_module.MonthlyWindow(cur)
	const limit = 73 * time.Hour // lateStartMinWindow + lateStartLead
	if left := time.Until(endsAt); left > limit-time.Minute && left < limit+time.Hour {
		t.Skip("real clock too close to the late-start limit")
	}
	wantCode := 201
	if time.Until(endsAt) < limit {
		wantCode = 409
	}
	code, out = e.do("POST", "/api/admin/events/generate-monthly", map[string]any{"media_type": "movie", "period": cur, "late_start": true}, tok)
	if code != wantCode {
		t.Fatalf("current late start: want %d, got %d: %v", wantCode, code, out)
	}
	if code == 409 && out["code"] != "VOTING_WINDOW_TOO_SHORT" {
		t.Errorf("want VOTING_WINDOW_TOO_SHORT, got %v", out)
	}
}

// Worker catch-up: a current round with no row at all is drafted late, never auto-published, and
// never recreated after an admin deletes it.
func TestRoundSchedulerCatchUpDraftsCurrentRound(t *testing.T) {
	e := newEnv(t)
	ctx := context.Background()
	at := lateEnough

	generated, published, err := schedulerAt(e.db, at).RunOnce(ctx)
	if err != nil || generated != 2 || published != 0 {
		t.Fatalf("want 2 catch-up drafts, got generated=%d published=%d err=%v", generated, published, err)
	}
	for _, mt := range []string{"movie", "tv"} {
		if n := e.count(`SELECT COUNT(*) FROM events WHERE type = 'vote_monthly' AND media_type = ? AND period = '2026-11'
			AND status = 'draft' AND auto_generated AND NOT auto_publish AND starts_at = ? AND ends_at = ?`,
			mt, at.Add(time.Hour), lateEnds); n != 1 {
			t.Errorf("%s: want one late draft with auto_publish=false, got %d", mt, n)
		}
	}
	if n := e.count(`SELECT COUNT(*) FROM admin_audit_logs WHERE action = ? AND admin_id IS NULL AND meta_data->>'late_start' = 'true'`,
		string(admin_module.ActionEventAutoGenerated)); n != 2 {
		t.Errorf("want 2 system audit rows with late_start, got %d", n)
	}

	// Even once due, the worker leaves it for an admin.
	if _, published, err := schedulerAt(e.db, at.Add(time.Hour)).RunOnce(ctx); err != nil || published != 0 {
		t.Fatalf("catch-up draft must not be auto-published: published=%d err=%v", published, err)
	}
	if n := e.count(`SELECT COUNT(*) FROM events WHERE status = 'published'`); n != 0 {
		t.Errorf("nothing may be published, got %d", n)
	}

	// An admin delete is final.
	if err := e.db.Where("1 = 1").Delete(&event_module.Event{}).Error; err != nil {
		t.Fatal(err)
	}
	if generated, _, err := schedulerAt(e.db, at.Add(2*time.Hour)).RunOnce(ctx); err != nil || generated != 0 {
		t.Fatalf("deleted round must stay deleted: generated=%d err=%v", generated, err)
	}
	if n := roundCount(e, "vote_monthly", "movie", "2026-11"); n != 1 {
		t.Errorf("want only the soft-deleted row, got %d", n)
	}
}

